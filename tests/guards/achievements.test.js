const test = require('node:test');
const assert = require('node:assert/strict');
const mongoose = require('mongoose');
mongoose.set('autoCreate', false).set('autoIndex', false);
const { randomUUID } = require('node:crypto');
process.env.JWT_SECRET = 'tp51-local-pagination-test';
test('TP5.1: badge concurrency, evidence-only backfill, preserved ledger and owner-bound history', async () => {
  const {MongoMemoryReplSet}=require('mongodb-memory-server');
  const repl=process.env.GUARD_MONGO_URI?null:await MongoMemoryReplSet.create({binary:{version:'7.0.14'},replSet:{count:1}});
  const uri=process.env.GUARD_MONGO_URI||repl.getUri();
  assert.ok(['localhost','127.0.0.1'].includes(new URL(uri).hostname));
  await mongoose.connect(uri,{dbName:'collegehubs_demo_tp51_'+randomUUID().replaceAll('-','')});
  try {
    const db=mongoose.connection.db;
    const Award=require('../../services/core/models/AchievementAward');
    await Award.createCollection();await Award.createIndexes();
    const {project,read}=require('../../services/core/services/achievementService');
    const reads=require('../../services/core/services/auraReadService');
    const {titleFor}=require('../../services/core/config/achievements');
    for(const [points,title] of [[0,'Seed'],[99,'Seed'],[100,'Contributor'],[299,'Contributor'],[300,'Collaborator'],[999,'Collaborator'],[1000,'Mentor'],[9999,'Mentor']]) assert.equal(titleFor(points),title);
    const id=()=>new mongoose.Types.ObjectId(), owner={userId:id(),hubId:id()}, other={userId:id(),hubId:owner.hubId}, foreign={userId:id(),hubId:id()};
    const context={userId:String(owner.userId),hubId:String(owner.hubId)};
    await db.collection('users').insertMany([{_id:owner.userId,hubId:owner.hubId,rankTitle:'Mentor',achievements:['fake']},{_id:other.userId,hubId:other.hubId}]);
    await db.createCollection('hubs');await db.createCollection('channels');
    assert.ok((await read(context)).every(row=>!row.earned),'legacy fields are not evidence');
    await db.collection('aurabalances').insertOne({...owner,total:125,engagement:125,externalBonus:0,version:2,asOf:new Date()});
    const at=new Date('2026-10-01T12:00:00Z');
    await db.collection('nativefacts').insertMany(['code.shared','study.completed'].map((type,i)=>({...owner,type,eventId:'native-'+i,occurredAt:at,status:'rules_inactive'})));
    await db.collection('dailyactivities').insertMany(Array.from({length:7},(_,i)=>({...owner,dayKey:'2026-10-0'+(i+1),firstOccurredAt:new Date(at.getTime()+i*86400000),timezonePolicyVersion:1})));
    await db.collection('auraevents').insertMany(Array.from({length:6},(_,i)=>({...owner,eventId:'node-'+i,type:'learn.node_mastered',metadata:{nodeId:'node-'+(i%3)},canonical:true,awardedAura:i===0?0:15,policyReason:i===0?'source_cap':'awarded',ruleVersion:'learn-demo-v1',occurredAt:at,receivedAt:at,dayKey:'2026-10-01'})));
    await db.collection('auraevents').insertMany([{...owner,eventId:'duplicate',canonical:false,type:'learn.node_mastered',metadata:{nodeId:'not-eligible'},awardedAura:0},{...other,eventId:'private-peer',canonical:true},{...foreign,eventId:'private-hub',canonical:true}]);
    const before=JSON.stringify(await db.collection('aurabalances').find().toArray()), receipts=JSON.stringify(await db.collection('auraevents').find().toArray());
    await Promise.all(Array.from({length:8},()=>project(db,owner)));
    const awards=await Award.find().lean();assert.equal(awards.length,4);
    assert.ok((await read(context)).every(row=>row.earned));
    assert.equal(awards.find(row=>row.badgeId==='academic-explorer').evidence.length,3);
    assert.equal(await Award.countDocuments({userId:other.userId}),0);
    const first=await reads.history(context,{limit:'2'});
    const second=await reads.history(context,{limit:'2',cursor:first.nextCursor});
    const third=await reads.history(context,{limit:'2',cursor:second.nextCursor});
    assert.equal(new Set([...first.items,...second.items,...third.items].map(row=>row.eventId)).size,6);
    assert.equal(third.nextCursor,null);
    assert.ok([...first.items,...second.items,...third.items].some(row=>row.awardedAura===0));
    await assert.rejects(reads.history({userId:String(other.userId),hubId:String(other.hubId)},{cursor:first.nextCursor}),{status:400});
    await assert.rejects(reads.history({userId:context.userId,hubId:String(foreign.hubId)},{cursor:first.nextCursor}),{status:400});
    await assert.rejects(reads.history(context,{cursor:first.nextCursor+'x'}),{status:400});
    await assert.rejects(reads.history(context,{userId:String(other.userId)}),{status:400});
    await assert.rejects(reads.history(context,{limit:'51'}),{status:400});
    const migration=require('../../services/core/migrations/0004_achievements');
    const {migrate}=require('../../services/core/migrations/runner');
    const catalog=[{id:'0004_achievements',checksum:'a'.repeat(64),up:migration,prepare:migration.prepare}];
    await Award.deleteMany({});
    assert.equal((await migrate(mongoose.connection.getClient(),db.databaseName,{migrations:catalog})).dryRun,true);
    assert.equal(await Award.countDocuments(),0);
    const partial=await migrate(mongoose.connection.getClient(),db.databaseName,{migrations:catalog,dryRun:false,batchSize:1,maxBatches:1});assert.equal(partial.complete,false);
    await migrate(mongoose.connection.getClient(),db.databaseName,{migrations:catalog,dryRun:false,batchSize:1});
    const saved=JSON.stringify(await Award.find().sort({badgeId:1}).lean());
    await migrate(mongoose.connection.getClient(),db.databaseName,{migrations:catalog,dryRun:false});
    assert.equal(JSON.stringify(await Award.find().sort({badgeId:1}).lean()),saved);
    assert.equal(await Award.countDocuments(),4);
    assert.equal(JSON.stringify(await db.collection('aurabalances').find().toArray()),before);
    assert.equal(JSON.stringify(await db.collection('auraevents').find().toArray()),receipts);
    assert.equal((await db.collection('users').findOne({_id:owner.userId})).rankTitle,'Mentor');
  } finally {await mongoose.connection.dropDatabase();await mongoose.disconnect();await repl?.stop();}
});
